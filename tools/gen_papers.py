#!/usr/bin/env python3
"""Generate src/libmx870/papers.inc: exact ESC (p geometry per paper size,
taken from the ESC (p templates of the user's copy of cnm_0367.dll.

Output per paper (1/600 inch): width, length, bordered x/width,
bordered length for top margin 70 and 118, borderless width/length.
"""
import re
import struct
import sys

data = open(sys.argv[1], 'rb').read()
geo = {}
for m in re.finditer(rb'\x1b\(p\x2e\x00', data):
    f = struct.unpack('>HHHHIH8i', data[m.end():m.end() + 46])
    ax, ay, aw, al, pw, pl = f[6], f[7], f[8], f[9], f[12], f[13]
    g = geo.setdefault((pw, pl), {})
    if ax == -70:
        g['bl'] = (aw, al)
    elif ax > 0:
        g['x'], g['w'] = ax, aw
        g['l%d' % ay] = al

print('/* Generated by tools/gen_papers.py from the Windows ESC (p templates. */')
print('/* width, length, x0, area_w, area_l (top 70), area_l (top 118), borderless w, l */')
for (pw, pl), g in sorted(geo.items()):
    l70 = g.get('l70', g.get('l118', 0) + 47 if 'l118' in g else 0)
    l118 = g.get('l118', l70 - 47)
    bw, bh = g.get('bl', (0, 0))
    print(f'  {{{pw}, {pl}, {g.get("x", 80)}, {g.get("w", 0)}, {l70}, {l118}, {bw}, {bh}}},')
