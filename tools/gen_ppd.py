#!/usr/bin/env python3
"""Generate the MX870 PPD from libmx870's tables, so paper sizes, printable
areas and media types stay identical in the driver and the encoder.

Usage: gen_ppd.py PAPERS_INC FILTER_PATH > canon-mx870.ppd

PAPERS_INC is build/generated/papers.inc, generated from your copy of the
Windows driver (see tools/extract_assets.sh).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIB = ROOT / 'src' / 'libmx870'

PPD_NAMES = {  # PPD PageSize keyword for each libmx870 paper name
    'iso_a4_210x297mm': 'A4', 'na_letter_8.5x11in': 'Letter', 'na_legal_8.5x14in': 'Legal',
    'iso_a5_148x210mm': 'A5', 'jis_b5_182x257mm': 'B5', 'na_index-4x6_4x6in': '4x6',
    'na_5x7_5x7in': '5x7', 'na_govt-letter_8x10in': '8x10', 'na_index-4x8_4x8in': '4x8',
    'om_wide_101.6x180.6mm': 'w288h512', 'oe_photo-l_3.5x5in': 'L', 'om_2l_127x178mm': '2L',
    'om_card_55x91mm': 'w156h258', 'jpn_hagaki_100x148mm': 'Postcard',
    'om_oufuku-landscape_200x148mm': 'DoublePostcardRotated', 'na_number-10_4.125x9.5in': 'Env10',
    'iso_dl_110x220mm': 'EnvDL', 'jpn_you4_105x235mm': 'EnvYou4', 'om_you6_98x190mm': 'EnvYou6',
    'jpn_chou3_120x235mm': 'EnvChou3', 'jpn_chou4_90x205mm': 'EnvChou4',
}


def tables(papers_inc):
    src = (LIB / 'tables.c').read_text()
    papers = re.findall(r'\{"([^"]+)",\s*"([^"]+)",\s*0x[0-9a-f]+,\s*(\d+),\s*(\d+)\}', src)
    media = re.findall(r'\{"([^"]+)",\s*"([^"]+)",\s*0x[0-9a-f]+,\s*0x[0-9a-f]+,\s*0x[0-9a-f]+,\s*(\d)\}', src)
    geo = {}
    for line in Path(papers_inc).read_text().splitlines():
        nums = re.findall(r'-?\d+', line)
        if line.strip().startswith('{') and len(nums) == 8:
            w, l, x0, aw, l70, l118, bw, bl = map(int, nums)
            geo[(w, l)] = (x0, aw, l70, bw)
    return papers, media, geo


def pt(v):
    return f'{v * 72 / 600:.2f}'


def main(papers_inc, filter_path):
    papers, media, geo = tables(papers_inc)
    out = []
    w = out.append

    w('*PPD-Adobe: "4.3"')
    w('*% Canon PIXMA MX870 - generated by tools/gen_ppd.py from libmx870 tables')
    w('*FormatVersion: "4.3"')
    w('*FileVersion: "0.1.0"')
    w('*LanguageVersion: English')
    w('*LanguageEncoding: ISOLatin1')
    w('*PCFileName: "MX870.PPD"')
    w('*Manufacturer: "Canon"')
    w('*Product: "(PIXMA MX870)"')
    w('*Product: "(MX870 series)"')
    w('*ModelName: "Canon MX870 series"')
    w('*ShortNickName: "Canon MX870 series"')
    w('*NickName: "Canon MX870 series, libmx870 0.1"')
    w('*1284DeviceID: "MFG:Canon;MDL:MX870 series;"')
    w('*PSVersion: "(3010.000) 0"')
    w('*LanguageLevel: "3"')
    w('*ColorDevice: True')
    w('*DefaultColorSpace: RGB')
    w('*FileSystem: False')
    w('*Throughput: "5"')
    w('*LandscapeOrientation: Plus90')
    w('*TTRasterizer: Type42')
    w('*cupsVersion: 2.3')
    w('*cupsModelNumber: 870')
    w('*cupsManualCopies: True')
    w(f'*cupsFilter2: "application/vnd.cups-raster application/vnd.cups-raster 100 {filter_path}"')
    w('*cupsLanguages: "en"')
    w('*DefaultResolution: 600dpi')
    w('')

    sizes = []
    for name, label, pw, pl in papers:
        pw, pl = int(pw), int(pl)
        if name not in PPD_NAMES or (pw, pl) not in geo:
            continue
        x0, aw, l70, bw = geo[(pw, pl)]
        key = PPD_NAMES[name]
        sizes.append((key, label, pw, pl, (x0, 70, aw, l70), False))
        if bw:
            sizes.append((key + '.Fullbleed', label + ' (Borderless)', pw, pl, None, True))

    w('*OpenUI *PageSize/Media Size: PickOne')
    w('*OrderDependency: 10 AnySetup *PageSize')
    w('*DefaultPageSize: A4')
    for key, label, pw, pl, _, bl in sizes:
        w(f'*PageSize {key}/{label}: "<</PageSize[{pt(pw)} {pt(pl)}]/ImagingBBox null/cupsInteger1 {int(bl)}>>setpagedevice"')
    w('*CloseUI: *PageSize')
    w('')
    w('*OpenUI *PageRegion/Media Size: PickOne')
    w('*OrderDependency: 10 AnySetup *PageRegion')
    w('*DefaultPageRegion: A4')
    for key, label, pw, pl, _, bl in sizes:
        w(f'*PageRegion {key}/{label}: "<</PageSize[{pt(pw)} {pt(pl)}]/ImagingBBox null/cupsInteger1 {int(bl)}>>setpagedevice"')
    w('*CloseUI: *PageRegion')
    w('')
    w('*DefaultImageableArea: A4')
    w('*DefaultPaperDimension: A4')
    for key, label, pw, pl, area, bl in sizes:
        if bl:
            w(f'*ImageableArea {key}: "0 0 {pt(pw)} {pt(pl)}"')
        else:
            x0, y0, aw, al = area
            w(f'*ImageableArea {key}: "{pt(x0)} {pt(pl - y0 - al)} {pt(x0 + aw)} {pt(pl - y0)}"')
        w(f'*PaperDimension {key}: "{pt(pw)} {pt(pl)}"')
    w('')

    w('*OpenUI *MediaType/Media Type: PickOne')
    w('*OrderDependency: 20 AnySetup *MediaType')
    w('*DefaultMediaType: stationery')
    for name, label, _ in media:
        w(f'*MediaType {name}/{label}: "<</MediaType({name})>>setpagedevice"')
    w('*CloseUI: *MediaType')
    w('')

    w('*OpenUI *cupsPrintQuality/Print Quality: PickOne')
    w('*OrderDependency: 20 AnySetup *cupsPrintQuality')
    w('*DefaultcupsPrintQuality: Normal')
    w('*cupsPrintQuality Draft/Draft: "<</HWResolution[300 300]/cupsInteger0 1>>setpagedevice"')
    w('*cupsPrintQuality Normal/Normal: "<</HWResolution[600 600]/cupsInteger0 2>>setpagedevice"')
    w('*cupsPrintQuality High/High: "<</HWResolution[600 600]/cupsInteger0 3>>setpagedevice"')
    w('*CloseUI: *cupsPrintQuality')
    w('')

    w('*OpenUI *ColorModel/Color Mode: PickOne')
    w('*OrderDependency: 10 AnySetup *ColorModel')
    w('*DefaultColorModel: RGB')
    w('*ColorModel RGB/Color: "<</cupsColorOrder 0/cupsColorSpace 1/cupsBitsPerColor 8>>setpagedevice"')
    w('*ColorModel Gray/Grayscale: "<</cupsColorOrder 0/cupsColorSpace 18/cupsBitsPerColor 8>>setpagedevice"')
    w('*CloseUI: *ColorModel')
    w('')

    w('*OpenUI *InputSlot/Paper Source: PickOne')
    w('*OrderDependency: 20 AnySetup *InputSlot')
    w('*DefaultInputSlot: Auto')
    w('*InputSlot Auto/Automatic: "<</MediaPosition 0>>setpagedevice"')
    w('*InputSlot Rear/Rear Tray: "<</MediaPosition 1>>setpagedevice"')
    w('*InputSlot Cassette/Cassette: "<</MediaPosition 2>>setpagedevice"')
    w('*CloseUI: *InputSlot')
    w('')

    w('*OpenUI *Duplex/2-Sided Printing: PickOne')
    w('*OrderDependency: 20 AnySetup *Duplex')
    w('*DefaultDuplex: None')
    w('*Duplex None/Off: "<</Duplex false>>setpagedevice"')
    w('*Duplex DuplexNoTumble/Long-Edge (Portrait): "<</Duplex true/Tumble false>>setpagedevice"')
    w('*Duplex DuplexTumble/Short-Edge (Landscape): "<</Duplex true/Tumble true>>setpagedevice"')
    w('*CloseUI: *Duplex')
    w('')

    # Duplex is for plain paper with a border, as in the Windows driver's modes.
    for name, _, photo in media:
        if photo == '1':
            for d in ('DuplexNoTumble', 'DuplexTumble'):
                w(f'*UIConstraints: *MediaType {name} *Duplex {d}')
                w(f'*UIConstraints: *Duplex {d} *MediaType {name}')
    for key, *_, bl in sizes:
        if bl:
            for d in ('DuplexNoTumble', 'DuplexTumble'):
                w(f'*UIConstraints: *PageSize {key} *Duplex {d}')
                w(f'*UIConstraints: *Duplex {d} *PageSize {key}')
    w('')
    w('*% End of PPD')
    sys.stdout.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
