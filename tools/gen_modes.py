#!/usr/bin/env python3
"""Generate src/libmx870/modes.inc from extract_modes.py output.

Mode 7 records (extra slots 7..10, Photo Paper Pro II quality 4) are skipped:
the meaning of their extra planes is not decoded yet.
"""
import json
import sys

modes = json.load(open(sys.argv[1]))
print('/* Generated by tools/gen_modes.py from the Windows driver mode records. */')
print('/* model_byte, media, quality, duplex, dpi, t_header[3], {info, levels} x 13 */')
dups = {}
for m in modes:
    key = (m['model_byte'], m['media'], m['quality'])
    dups[key] = dups.get(key, 0) + 1
for m in modes:
    if any(i['slot'] > 6 for i in m['inks']):
        continue
    key = (m['model_byte'], m['media'], m['quality'])
    # Plain quality 3 exists twice; Gutenprint marks the ternary (5 px/byte)
    # inkset as the duplex variant and the 4-bit one as non-duplex.
    duplex = int(dups[key] > 1 and bool(m['inks'][0]['info'] & 0x20))
    t = bytes.fromhex(m['t'].replace(' ', ''))
    slots = ', '.join(f'{{0x{t[3 + 3 * i]:02x}, {t[5 + 3 * i]}}}' for i in range(13))
    hdr = ', '.join(f'0x{b:02x}' for b in t[:3])
    print(f'  {{0x{m["model_byte"]:02x}, 0x{m["media"]:02x}, {m["quality"]}, {duplex}, {m["dpi"][0]}, '
          f'{{{hdr}}}, {{{slots}}}}},')
